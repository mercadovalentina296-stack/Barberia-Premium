create table if not exists public.usuarios (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null,
  email varchar(190) not null unique,
  telefono varchar(30),
  password_hash varchar(200) not null,
  rol varchar(20) not null default 'cliente' check (rol in ('cliente','admin')),
  creado_en timestamptz not null default now()
);

create table if not exists public.servicios (
  id bigint generated by default as identity primary key,
  nombre varchar(120) not null,
  descripcion text,
  precio numeric(10,2) not null default 0,
  duracion integer not null default 30,
  activo smallint not null default 1 check (activo in (0,1))
);

create table if not exists public.reservas (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios(id),
  servicio_id bigint not null references public.servicios(id),
  fecha date not null,
  hora time not null,
  estado varchar(20) not null default 'pendiente' check (estado in ('pendiente','confirmada','cancelada')),
  observaciones text,
  creada_en timestamptz not null default now()
);
create unique index if not exists uq_reserva_horario_activo
  on public.reservas(fecha, hora) where estado in ('pendiente','confirmada');

create table if not exists public.opiniones (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios(id),
  puntuacion smallint not null check (puntuacion between 1 and 5),
  comentario text not null,
  aprobada smallint not null default 0 check (aprobada in (0,1)),
  fecha timestamptz not null default now()
);

create table if not exists public.galeria (
  id bigint generated by default as identity primary key,
  titulo varchar(160) not null,
  imagen varchar(500) not null,
  descripcion text,
  activa smallint not null default 1 check (activa in (0,1)),
  fecha timestamptz not null default now()
);

create table if not exists public.promociones (
  id bigint generated by default as identity primary key,
  titulo varchar(160) not null,
  descripcion text,
  descuento numeric(5,2) not null default 0,
  fecha_inicio date not null,
  fecha_fin date not null,
  activa smallint not null default 1 check (activa in (0,1)),
  check (fecha_fin >= fecha_inicio)
);

create index if not exists idx_reservas_usuario on public.reservas(usuario_id);
create index if not exists idx_opiniones_aprobada on public.opiniones(aprobada);
create index if not exists idx_galeria_activa on public.galeria(activa);
create index if not exists idx_promociones_activas on public.promociones(activa);

insert into public.servicios (nombre, descripcion, precio, duracion, activo)
select v.nombre, v.descripcion, v.precio, v.duracion, 1
from (values
 ('Corte clásico', 'Corte tradicional y prolijo.', 5000, 30),
 ('Barba', 'Perfilado y arreglo de barba.', 3000, 20),
 ('Corte + barba', 'Servicio completo de corte y barba.', 7000, 50)
) as v(nombre, descripcion, precio, duracion)
where not exists (select 1 from public.servicios s where s.nombre = v.nombre);

